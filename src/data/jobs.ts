function events(id: string, deliveredAt: string): StatusEvent[] {
  const steps: JobStatus[] = [
    "accepted",
    "en_route_pickup",
    "arrived_pickup",
    "picked_up",
    "in_transit",
    "arrived_dropoff",
    "delivered",
  ];
  const end = new Date(deliveredAt).getTime();
  return steps.map((status, index) => ({
    id: `${id}-${status}`,
    status,
    at: new Date(end - (steps.length - 1 - index) * 8 * 60 * 1000).toISOString(),
    gps: gps(37.39 + index * 0.012, -77.56 + index * 0.008),
  }));
}

function custody(id: string, personFrom: string, placeFrom: string, personTo: string, placeTo: string, at: string): CustodyEntry[] {
  const start = new Date(new Date(at).getTime() - 30 * 60 * 1000).toISOString();
  return [
    { id: `${id}-c1`, action: "Collected from", person: personFrom, place: placeFrom, at: start, gps: gps(37.44, -77.62) },
    { id: `${id}-c2`, action: "Delivered to", person: personTo, place: placeTo, at, gps: gps(37.52, -77.48) },
  ];
}

